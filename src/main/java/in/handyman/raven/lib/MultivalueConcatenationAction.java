  public void processSingleEntityMultiValueLineItems(List<MultiValueUniquenessInput> multiValueInputs,
                                                     List<MultiValueUniquenessInput> consolidatedInputs) {
    logger.info(logMarker, "====== CASE 1: SINGLE ENTITY MULTI-VALUE PROCESSING STARTED ======");
    logger.info(logMarker, "Processing {} multi_value records.", multiValueInputs.size());

    List<MultiValueUniquenessInput> normalizedMultiValueInputs = new ArrayList<>();
    String valueDelimiter = ",";
    int totalSplitRecordCount = 0;
    int multiValueItemCount = 0;

    for (MultiValueUniquenessInput currentInput : multiValueInputs) {
      String rawAnswerValue = currentInput.getAnswer();

      if (rawAnswerValue != null && rawAnswerValue.contains(valueDelimiter)) {
        multiValueItemCount++;
        String[] splitValues = rawAnswerValue.split(valueDelimiter);

        logger.debug(logMarker, "Splitting multi-value - SorItemName: {}, ValueCount: {}, DocumentId: {}, GroupId: {}, BatchId: {}",
                currentInput.getSorItemName(), splitValues.length, currentInput.getDocumentId(), currentInput.getGroupId(), currentInput.getBatchId());

        appendFilterDecisionMessage(currentInput,
                String.format("Split and removed due to multiple values (%s). Individual values will be processed.",
                        currentInput.getSorItemName()));

        int splitRecordCount = 0;
        for (String singleValue : splitValues) {
          String trimmedValue = singleValue.trim();
          if (!trimmedValue.isEmpty()) {
            MultiValueUniquenessInput clonedInput = cloneUniquenessInputRecord(currentInput);
            clonedInput.setAnswer(trimmedValue);
            appendFilterDecisionMessage(clonedInput,
                    String.format("Normalized from a multi-value. Original item: %s", currentInput.getSorItemName()));
            normalizedMultiValueInputs.add(clonedInput);
            splitRecordCount++;
            totalSplitRecordCount++;
          }
        }
        logger.debug(logMarker, "Split item {} into {} new records.", currentInput.getSorItemName(), splitRecordCount);
      } else {
        normalizedMultiValueInputs.add(currentInput);
      }
    }

    logger.info(logMarker, "Normalization Stats - Items with multiple values: {}, Total splits created: {}",
            multiValueItemCount, totalSplitRecordCount);
    logger.info(logMarker, "List size expanded from {} to {}.", multiValueInputs.size(), normalizedMultiValueInputs.size());

    // De-duplication phase
    List<MultiValueUniquenessInput> deduplicatedOutputs = new ArrayList<>();
    Set<String> uniquenessKeySet = new HashSet<>();
    int duplicateCount = 0;
    int uniqueCount = 0;

    for (MultiValueUniquenessInput currentInput : normalizedMultiValueInputs) {

      String uniquenessKey = String.format("%s|%s|%s", currentInput.getOriginId(), currentInput.getSorItemName(), currentInput.getAnswer());

      if (uniquenessKeySet.add(uniquenessKey)) {
        uniqueCount++;

        String baseReason = currentInput.getMessage() != null && currentInput.getMessage().startsWith("Normalized")
                ? currentInput.getMessage() + " Retained as unique."
                : "Retained as a unique multi_value item.";
        appendFilterDecisionMessage(currentInput, baseReason);
        deduplicatedOutputs.add(currentInput);

        logger.debug(logMarker, "Retained unique item - SorItemName: {}, Score: {}, DocumentId: {}, GroupId: {}, BatchId: {}",
                currentInput.getSorItemName(), currentInput.getScore(), currentInput.getDocumentId(), currentInput.getGroupId(), currentInput.getBatchId());
      } else {
        duplicateCount++;

        appendFilterDecisionMessage(currentInput,
                "Removed as a duplicate multi_value item (same value/score found in another page/instance).");
        deduplicatedOutputs.add(currentInput);

        logger.debug(logMarker, "Removed duplicate - SorItemName: {}, DocumentId: {}, GroupId: {}, BatchId: {}",
                currentInput.getSorItemName(), currentInput.getDocumentId(), currentInput.getGroupId(), currentInput.getBatchId());
      }
    }

    logger.info(logMarker, "De-duplication Stats - Unique retained: {}, Duplicates removed: {}", uniqueCount, duplicateCount);
    logger.info(logMarker, "====== CASE 1: SINGLE ENTITY MULTI-VALUE PROCESSING COMPLETED ======");

    consolidatedInputs.addAll(deduplicatedOutputs);
  }


