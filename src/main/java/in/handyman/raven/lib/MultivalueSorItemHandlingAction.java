    public void decryptAnswers(List<MultivalueSorItemHandlingActionInput> inputList, InticsIntegrity encryption) {
        if (inputList == null || inputList.isEmpty()) {
            return;
        }

        // Step 1: Convert to EncryptionRequestClass
        List<EncryptionRequestClass> encryptionRequests = inputList.stream()
                // Using `isEncrypted` property from the input object to determine if decryption is needed
                .filter(obj -> "true".equalsIgnoreCase(obj.getIsEncrypted())).filter(obj -> obj.getSorItemAttributionId() != null && obj.getAnswer() != null && !obj.getAnswer().isEmpty()).map(obj -> new EncryptionRequestClass(AES_256, obj.getAnswer(), String.valueOf(obj.getSorItemAttributionId()))).collect(Collectors.toList());
        log.info(aMarker, "Total records to decrypt for answers (Input): {}", encryptionRequests.size());

        if (encryptionRequests.isEmpty()) return;

        try {
            // Step 2: Call external Protegrity API
            List<EncryptionRequestClass> responseList = encryption.decrypt(encryptionRequests);

            // Step 3: Build a lookup map from response (Key: SorItemAttributionId)
            Map<Long, String> decryptedMap = responseList.stream().filter(item -> item.getKey() != null && item.getKey().matches("\\d+")).collect(Collectors.toMap(item -> Long.parseLong(item.getKey()), EncryptionRequestClass::getValue));

            // Step 4: Update original list
            for (MultivalueSorItemHandlingActionInput item : inputList) {
                if (item.getSorItemAttributionId() != null && decryptedMap.containsKey(item.getSorItemAttributionId())) {
                    item.setAnswer(decryptedMap.get(item.getSorItemAttributionId()));
                }
            }
        } catch (Exception e) {
            log.error(aMarker, "Decryption failed for Answers on input data.", e);
            // Depending on requirements, you might throw or handle gracefully.
        }
    }

