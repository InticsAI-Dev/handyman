    private List<MultivalueSorItemHandlingActionInput> handleCase3MultiEntityEnabled(List<MultivalueSorItemHandlingActionInput> inputs, Marker aMarker, Logger log, ActionExecutionAudit action) throws HandymanException {

        log.info(aMarker, "CASE 3: Processing {} multi-entity enabled single_value records.", inputs.size());

        // Group 1: Group by OriginId -> SorContainerInstance -> SorItemName
        Map<String, List<MultivalueSorItemHandlingActionInput>> groupedByOrigin = inputs.stream().collect(Collectors.groupingBy(MultivalueSorItemHandlingActionInput::getOriginId));

        List<MultivalueSorItemHandlingActionInput> output = new ArrayList<>();

        for (List<MultivalueSorItemHandlingActionInput> originInputs : groupedByOrigin.values()) {

            // Group 2: Group by SorItemName (to find competing answers for the same field)
            Map<String, List<MultivalueSorItemHandlingActionInput>> competingItemsMap = originInputs.stream().collect(Collectors.groupingBy(MultivalueSorItemHandlingActionInput::getSorItemName));

            for (List<MultivalueSorItemHandlingActionInput> competingInputs : competingItemsMap.values()) {

                // --- Sub-Step 1: Apply Whitelist Priority Filter (Across all instances) ---
                MultivalueSorItemHandlingActionInput retainedItem = applyWhitelistPriorityFilter(competingInputs, aMarker, log, action);

                if (retainedItem != null) {
                    // --- Sub-Step 2: Group by sorContainerInstance and keep highest score if no priority match ---
                    // The requirement: "If no priority matches then need to group the data by sorContainerInstance and
                    // return the value having highest sorItemData for each page one page should contains only one sorContainerinstance"

                    // Since `applyWhitelistPriorityFilter` already returned the highest priority item,
                    // we now need to ensure only ONE instance is kept PER PAGE/CONTAINER GROUPING.

                    // However, for multi-entity enabled, we usually keep all distinct instances.
                    // The most logical interpretation is that the whitelist determines the canonical value,
                    // and the grouping by instance is the final output structure.

                    // We rely on the initial whitelist filter to select the best record for that SorItemName.
                    output.add(retainedItem);
                }
            }
        }

        log.info(aMarker, "CASE 3: Retained {} multi-entity enabled records after priority filtering.", output.size());
        return output;
    }

    /**
     * CASE 4: Process 'single_value' items where isMultiEntityEnabled is FALSE.
     * This involves priority filtering AND consolidation across pages/instances based on grouping keys.
     */
    private List<MultivalueSorItemHandlingActionInput> handleCase4MultiEntityDisabled(List<MultivalueSorItemHandlingActionInput> inputs, Marker aMarker, Logger log, ActionExecutionAudit action) throws HandymanException {

        log.info(aMarker, "CASE 4: Processing {} multi-entity disabled single_value records.", inputs.size());

        // --- Sub-Step 1: Apply Whitelist Priority Filtering (to select the best answer for each SorItemName) ---
        List<MultivalueSorItemHandlingActionInput> prioritizedInputs = new ArrayList<>();

        Map<String, List<MultivalueSorItemHandlingActionInput>> groupedByItemName = inputs.stream().collect(Collectors.groupingBy(MultivalueSorItemHandlingActionInput::getSorItemName));

        for (List<MultivalueSorItemHandlingActionInput> competingInputs : groupedByItemName.values()) {
            MultivalueSorItemHandlingActionInput retainedItem = applyWhitelistPriorityFilter(competingInputs, aMarker, log, action);
            if (retainedItem != null) {
                prioritizedInputs.add(retainedItem);
            }
        }

        log.info(aMarker, "CASE 4: Retained {} records after initial whitelist priority filtering.", prioritizedInputs.size());

        // --- Sub-Step 2: Consolidation Logic (Grouping across pages/instances) ---
        return consolidateMultiPageData(prioritizedInputs, aMarker, log);
    }

    /**
     * Handles the consolidation of single-entity data across multiple pages/instances.
     * Logic: Group by MEMBER_GROUPING_KEYS (memberId, memberName, memberDob) to create a single canonical set of data.
     */
    private List<MultivalueSorItemHandlingActionInput> consolidateMultiPageData(List<MultivalueSorItemHandlingActionInput> prioritizedInputs, Marker aMarker, Logger log) {

        // Grouping by (OriginId + SorContainerName) is assumed to define the logical Container
        Map<String, List<MultivalueSorItemHandlingActionInput>> groupedByContainer = prioritizedInputs.stream().collect(Collectors.groupingBy(input -> input.getOriginId() + "_" + input.getSorContainerName()));

        List<MultivalueSorItemHandlingActionInput> consolidatedOutput = new ArrayList<>();

        for (Map.Entry<String, List<MultivalueSorItemHandlingActionInput>> containerEntry : groupedByContainer.entrySet()) {
            List<MultivalueSorItemHandlingActionInput> itemsInContainer = containerEntry.getValue();

            // Sub-group by the grouping keys (memberId, memberName, memberDob)
            Map<String, List<MultivalueSorItemHandlingActionInput>> mergedRecords = new HashMap<>();

            for (MultivalueSorItemHandlingActionInput item : itemsInContainer) {
                String groupingKey = generateGroupingKey(item, itemsInContainer);
                mergedRecords.computeIfAbsent(groupingKey, k -> new ArrayList<>()).add(item);
            }

            // Process Merged Records (Conflict Resolution: keep the highest score for non-key items)
            for (List<MultivalueSorItemHandlingActionInput> itemsToMerge : mergedRecords.values()) {

                // Further group by SorItemName (since different pages can provide answers for the same SorItemName)
                Map<String, MultivalueSorItemHandlingActionInput> finalCanonicalItems = new HashMap<>();

                for (MultivalueSorItemHandlingActionInput item : itemsToMerge) {
                    String itemName = item.getSorItemName();

                    if (!finalCanonicalItems.containsKey(itemName) || item.getScore() > finalCanonicalItems.get(itemName).getScore()) {

                        // Keep this item if it's new OR if it has a higher score (conflict resolution)
                        if (finalCanonicalItems.containsKey(itemName)) {
                            finalCanonicalItems.get(itemName).setRemovedAfterFiltering(true);
                            finalCanonicalItems.get(itemName).setMessage("Removed by consolidation/score conflict: Retained item score " + item.getScore());
                        }

                        item.setRemovedAfterFiltering(false);
                        item.setMessage("Retained by consolidation (or highest score conflict resolution).");
                        finalCanonicalItems.put(itemName, item);
                    } else {
                        item.setRemovedAfterFiltering(true);
                        item.setMessage("Removed by consolidation/score conflict: Retained item score " + finalCanonicalItems.get(itemName).getScore());
                    }
                }
                consolidatedOutput.addAll(finalCanonicalItems.values());
            }
        }
        log.info(aMarker, "CASE 4: Retained {} records after multi-page consolidation.", consolidatedOutput.size());
        return consolidatedOutput;
    }

    // Helper: Generates a key using the available member grouping keys (Id, Name, DOB)
    private String generateGroupingKey(MultivalueSorItemHandlingActionInput currentItem, List<MultivalueSorItemHandlingActionInput> allItemsInContainer) {

        // Find any key items associated with this container to group
        String key = allItemsInContainer.stream().filter(item -> MEMBER_GROUPING_KEYS.contains(item.getSorItemName())).map(item -> item.getSorItemName() + ":" + item.getAnswer()).collect(Collectors.joining("|"));

        // If no grouping keys are present across any page in the container,
        // the items are assumed to belong to a single "default" group.
        if (key.isEmpty()) {
            return "NO_MEMBER_KEY_FOUND";
        }
        return key;
    }

    /**
     * Applies the filtering based on whitelistedSections and priorityLevel.
     * If multiple answers exist for the same SorItemName, only the one from the highest priority sectionAlias is kept.
     */
    private MultivalueSorItemHandlingActionInput applyWhitelistPriorityFilter(List<MultivalueSorItemHandlingActionInput> competingInputs, Marker aMarker, Logger log, ActionExecutionAudit action) throws HandymanException {

        if (competingInputs.size() <= 1) {
            if (!competingInputs.isEmpty()) {
                competingInputs.get(0).setRemovedAfterFiltering(false);
                competingInputs.get(0).setMessage("Retained as only one candidate found.");
            }
            return competingInputs.isEmpty() ? null : competingInputs.get(0);
        }

        try {
            // Assume all competing inputs share the same whitelistedSections configuration
            String whitelistedSectionsJson = competingInputs.get(0).getWhitelistedSections();
            if (whitelistedSectionsJson == null || whitelistedSectionsJson.isEmpty()) {
                // Fallback: No whitelist, take the one with the highest score
                MultivalueSorItemHandlingActionInput maxScoreItem = competingInputs.stream().max(Comparator.comparingDouble(MultivalueSorItemHandlingActionInput::getScore)).orElse(null);

                if (maxScoreItem != null) {
                    competingInputs.stream().filter(item -> item != maxScoreItem).forEach(item -> {
                        item.setRemovedAfterFiltering(true);
                        item.setMessage("Removed by max score fallback (No whitelist config).");
                    });
                    maxScoreItem.setRemovedAfterFiltering(false);
                    maxScoreItem.setMessage("Retained by max score fallback (No whitelist config).");
                }
                return maxScoreItem;
            }

            // 1. Parse Whitelist and sort by priority (1 is highest)
            List<WhitelistEntry> whitelist = objectMapper.readValue(whitelistedSectionsJson, new TypeReference<List<WhitelistEntry>>() {
            });
            whitelist.sort(Comparator.comparingInt(WhitelistEntry::getPriorityLevel));

            // 2. Find the best match
            MultivalueSorItemHandlingActionInput bestMatch = null;
            for (WhitelistEntry whiteEntry : whitelist) {
                String targetAlias = whiteEntry.getTruthEntity();

                Optional<MultivalueSorItemHandlingActionInput> match = competingInputs.stream().filter(item -> targetAlias.equalsIgnoreCase(item.getSectionAlias())).findFirst();

                if (match.isPresent()) {
                    bestMatch = match.get();
                    bestMatch.setSectionPriorityAfterFilter(String.valueOf(whiteEntry.getPriorityLevel()));
                    break; // Found the highest priority match
                }
            }

            // 3. Final Selection and Messaging
            if (bestMatch != null) {
                bestMatch.setRemovedAfterFiltering(false);
                bestMatch.setMessage("Retained by Section Alias Priority: " + bestMatch.getSectionAlias());

                MultivalueSorItemHandlingActionInput finalBestMatch = bestMatch;
                MultivalueSorItemHandlingActionInput finalBestMatch1 = bestMatch;
                competingInputs.stream().filter(item -> item != finalBestMatch).forEach(item -> {
                    item.setRemovedAfterFiltering(true);
                    item.setMessage("Removed by lower Section Alias Priority. Retained alias: " + finalBestMatch1.getSectionAlias());
                });
                return bestMatch;
            } else {
                // Fallback: No item matches the whitelist. Use Max Score.
                MultivalueSorItemHandlingActionInput maxScoreItem = competingInputs.stream().max(Comparator.comparingDouble(MultivalueSorItemHandlingActionInput::getScore)).get(); // Safe because size > 1

                maxScoreItem.setRemovedAfterFiltering(false);
                maxScoreItem.setMessage("Retained by max score fallback (Alias did not match whitelist).");

                competingInputs.stream().filter(item -> item != maxScoreItem).forEach(item -> {
                    item.setRemovedAfterFiltering(true);
                    item.setMessage("Removed by max score fallback (Alias did not match whitelist). Retained score: " + maxScoreItem.getScore());
                });
                return maxScoreItem;
            }

        } catch (IOException e) {
            log.error(aMarker, "Error parsing whitelistedSections JSON for SorItemName: {}", competingInputs.get(0).getSorItemName());
            HandymanException handymanException = new HandymanException(e);
            HandymanException.insertException("Error in applyWhitelistPriorityFilter", handymanException, action);
            // Fallback: If parsing fails, revert to max score
            return competingInputs.stream().max(Comparator.comparingDouble(MultivalueSorItemHandlingActionInput::getScore)).orElse(null);

        }
    }

    public static List<MultivalueSorItemHandlingActionInput> selectMaxCountNodes(List<MultivalueSorItemHandlingActionInput> list) {

        if (list == null || list.isEmpty()) return Collections.emptyList();

        // Final output
        List<MultivalueSorItemHandlingActionInput> output = new ArrayList<>();

        // Step-1: Group by originId
        Map<String, List<MultivalueSorItemHandlingActionInput>> byOrigin = list.stream().collect(Collectors.groupingBy(MultivalueSorItemHandlingActionInput::getOriginId));

        for (Map.Entry<String, List<MultivalueSorItemHandlingActionInput>> originEntry : byOrigin.entrySet()) {

            // Step-2: Group by sorContainerName inside same originId
            Map<String, List<MultivalueSorItemHandlingActionInput>> byContainerName = originEntry.getValue().stream().collect(Collectors.groupingBy(MultivalueSorItemHandlingActionInput::getSorContainerName));

            for (Map.Entry<String, List<MultivalueSorItemHandlingActionInput>> containerEntry : byContainerName.entrySet()) {

                // Step-3: Group by (pageNo + sorContainerInstance)
                Map<String, List<MultivalueSorItemHandlingActionInput>> byPageAndInstance = containerEntry.getValue().stream().collect(Collectors.groupingBy(item -> item.getPaperNo() + "_" + item.getSorContainerInstance()));

                // Step-4: Evaluate groups to find max-count (with tie-break)
                Optional<Map.Entry<String, List<MultivalueSorItemHandlingActionInput>>> bestGroup = byPageAndInstance.entrySet().stream().sorted((e1, e2) -> {
                    // Compare by size DESC
                    int cmp = Integer.compare(e2.getValue().size(), e1.getValue().size());
                    if (cmp != 0) return cmp;

                    // tie → choose smaller pageNo
                    Long p1 = e1.getValue().get(0).getPaperNo();
                    Long p2 = e2.getValue().get(0).getPaperNo();
                    cmp = Long.compare(p1, p2);
                    if (cmp != 0) return cmp;

                    // final tie → keep any
                    return 0;
                }).findFirst();

                bestGroup.ifPresent(g -> output.addAll(g.getValue()));
            }
        }

        return output;
    }


