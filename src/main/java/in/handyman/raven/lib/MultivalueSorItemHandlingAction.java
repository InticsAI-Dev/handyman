    static final class GroupKey {
        private final String originId;
        private final Integer paperNo;

        GroupKey(String originId, Integer paperNo) {
            this.originId = originId;
            this.paperNo = paperNo;
        }

        @Override
        public boolean equals(Object o) {
            if (this == o) return true;
            if (!(o instanceof GroupKey)) return false;
            GroupKey that = (GroupKey) o;
            return Objects.equals(originId, that.originId) && Objects.equals(paperNo, that.paperNo);
        }

        @Override
        public int hashCode() {
            return Objects.hash(originId, paperNo);
        }
    }

