    if ("missing".equals(status)) {
      log.warn(aMarker, "[{}] Table not found, skipping", fqn);
      rec.operation = "SKIPPED";
      return;
    }
    if ("false".equals(status)) {
      log.info(aMarker, "[{}] Regular table detected; running ONE-TIME SETUP", fqn);
      // Capture metrics BEFORE setup runs (the table still bears its original name)
      captureTableMetrics(jdbi, schema, table, rec);
      setupOneTable(jdbi, schema, table, window, rec);
      return;
    }
    if ("true".equals(status)) {
      log.info(aMarker, "[{}] Already partitioned; running DAILY MAINTENANCE", fqn);
      // Capture metrics on the partitioned parent (reltuples summed across children)
      captureTableMetrics(jdbi, schema, table, rec);
      maintainOneTable(jdbi, schema, table, window, rec);
      return;
    }
    log.warn(aMarker, "[{}] Unexpected relkind '{}', skipping", fqn, status);
    rec.operation = "SKIPPED";
