  /** Parsed representation of "db.partition.window.range" e.g. "10,4". */
  private static final class WindowRange {
    final int daysBack;
    final int daysForward;

    WindowRange(int daysBack, int daysForward) {
      if (daysBack < 0 || daysForward < 0) {
        throw new IllegalArgumentException(
                "Window values must be non-negative: back=" + daysBack + ", forward=" + daysForward);
      }
      this.daysBack = daysBack;
      this.daysForward = daysForward;
    }

    static WindowRange parse(String raw) {
      if (raw == null) {
        throw new IllegalArgumentException("Window range string must not be null");
      }
      final String[] parts = raw.split(",");
      if (parts.length != 2) {
        throw new IllegalArgumentException(
                "Invalid window format '" + raw + "': expected 'days_back,days_forward'");
      }
      final int back;
      final int fwd;
      try {
        back = Integer.parseInt(parts[0].trim());
        fwd = Integer.parseInt(parts[1].trim());
      } catch (NumberFormatException e) {
        throw new IllegalArgumentException(
                "Invalid window values in '" + raw + "': not integers", e);
      }
      return new WindowRange(back, fwd);
    }

    /** Total span: daysBack + daysForward + 1 (today). */
    int size() { return daysBack + daysForward + 1; }

    @Override
    public String toString() {
      return "WindowRange(back=" + daysBack + ", forward=" + daysForward + ")";
    }
  }

