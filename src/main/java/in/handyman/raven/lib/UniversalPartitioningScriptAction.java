  /** Parses "{1,3,5}" into [1, 3, 5] preserving order. */
  private static List<Integer> parsePgIntArray(String text) {
    if (text == null || text.isEmpty()) return new ArrayList<>();
    String trimmed = text.trim();
    if (trimmed.startsWith("{") && trimmed.endsWith("}")) {
      trimmed = trimmed.substring(1, trimmed.length() - 1);
    }
    if (trimmed.isEmpty()) return new ArrayList<>();
    return Arrays.stream(trimmed.split(","))
            .map(String::trim)
            .filter(s -> !s.isEmpty())
            .map(Integer::parseInt)
            .collect(Collectors.toList());
  }

  /** Parses "1 3 5" (pg_index.indkey format) into [1, 3, 5]. */
  private static List<Integer> parseSpaceSeparatedInts(String text) {
    if (text == null || text.isEmpty()) return new ArrayList<>();
    return Arrays.stream(text.trim().split("\\s+"))
            .filter(s -> !s.isEmpty())
            .map(Integer::parseInt)
            .collect(Collectors.toList());
  }

  /** Returns a new list with value appended if not already present. */
  private static List<String> appendIfMissing(List<String> list, String value) {
    if (list.contains(value)) return list;
    final List<String> copy = new ArrayList<>(list);
    copy.add(value);
    return copy;
  }

  /** Parses the "db.partition.tables" CSV into validated schema.table pairs. */
  private static List<TableEntry> parseTableEntries(String csv) {
    final List<TableEntry> result = new ArrayList<>();
    if (csv == null) return result;
    for (String raw : csv.split(",")) {
      final String trimmed = raw.trim();
      if (trimmed.isEmpty()) continue;

      final String[] parts = trimmed.split("\\.");
      if (parts.length != 2) {
        throw new IllegalArgumentException(
                "Invalid entry '" + trimmed + "': expected schema.table");
      }
      final String schema = parts[0].trim();
      final String table = parts[1].trim();

      if (!IDENT_PATTERN.matcher(schema).matches()
              || !IDENT_PATTERN.matcher(table).matches()) {
        throw new IllegalArgumentException(
                "Invalid identifier in '" + schema + "." + table + "'");
      }
      result.add(new TableEntry(schema, table));
    }
    return result;
  }

  /** Safely quotes a PostgreSQL identifier; rejects anything outside [a-zA-Z0-9_]. */
  private static String quoteIdent(String ident) {
    if (ident == null || ident.isEmpty()) {
      throw new IllegalArgumentException("Identifier must not be null or empty");
    }
    if (!IDENT_PATTERN.matcher(ident).matches()) {
      throw new IllegalArgumentException(
              "Invalid identifier: '" + ident + "' (must match " + IDENT_PATTERN.pattern() + ")");
    }
    return "\"" + ident + "\"";
  }

  /** Quotes a schema and table together as "schema"."table". */
  private static String quoteFqn(String schema, String table) {
    return quoteIdent(schema) + "." + quoteIdent(table);
  }

  /** Safely quotes a SQL literal by doubling embedded single quotes. */
  private static String quoteLiteral(String literal) {
    if (literal == null) return "NULL";
    return "'" + literal.replace("'", "''") + "'";
  }
