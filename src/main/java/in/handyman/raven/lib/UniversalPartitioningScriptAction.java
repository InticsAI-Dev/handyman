  /**
   * Captures cheap table metrics into the audit record:
   *   - totalRowCount: estimate via pg_class.reltuples (instant, no scan).
   *     For a partitioned parent (relkind='p'), reltuples on the parent is
   *     typically 0; we sum reltuples across its child partitions via
   *     pg_inherits to get a realistic estimate.
   *   - totalColumnCount: exact, from pg_attribute (fast catalog read).
   * Never throws — any failure leaves the fields null and logs a warning.
   * The metric query is intentionally outside any user transaction so it
   * never holds locks on application tables.
   */
  private void captureTableMetrics(Jdbi jdbi, String schema, String table, AuditRecord rec) {
    final String fqn = schema + "." + table;
    try {
      final Long rowCount = jdbi.withHandle(handle ->
              handle.createQuery(
                              "SELECT CASE " +
                                      "  WHEN c.relkind = 'p' THEN " +
                                      "    COALESCE((SELECT SUM(GREATEST(child.reltuples, 0))::bigint " +
                                      "              FROM pg_inherits inh " +
                                      "              JOIN pg_class child ON child.oid = inh.inhrelid " +
                                      "              WHERE inh.inhparent = c.oid), 0) " +
                                      "  WHEN c.relkind = 'r' THEN " +
                                      "    GREATEST(c.reltuples, 0)::bigint " +
                                      "  ELSE NULL " +
                                      "END AS row_estimate " +
                                      "FROM pg_class c " +
                                      "JOIN pg_namespace n ON n.oid = c.relnamespace " +
                                      "WHERE n.nspname = :schema AND c.relname = :table")
                      .bind("schema", schema)
                      .bind("table", table)
                      .mapTo(Long.class)
                      .findOne()
                      .orElse(null));

      final Integer colCount = jdbi.withHandle(handle ->
              handle.createQuery(
                              "SELECT count(*)::int FROM pg_attribute a " +
                                      "JOIN pg_class c     ON c.oid = a.attrelid " +
                                      "JOIN pg_namespace n ON n.oid = c.relnamespace " +
                                      "WHERE n.nspname = :schema AND c.relname = :table " +
                                      "  AND a.attnum > 0 AND NOT a.attisdropped")
                      .bind("schema", schema)
                      .bind("table", table)
                      .mapTo(Integer.class)
                      .findOne()
                      .orElse(null));

      rec.totalRowCount    = rowCount;
      rec.totalColumnCount = colCount;
      log.info(aMarker, "[{}] Table metrics captured: rows~={}, columns={}",
              fqn, rowCount, colCount);
    } catch (Exception e) {
      // Never fail the run for an audit detail
      log.warn(aMarker, "[{}] Could not capture table metrics: {}", fqn, e.getMessage());
    }
  }

  /** Tries created_date first, then created_on; must be timestamp. */
  private Optional<String> resolvePartitionColumn(Jdbi jdbi, String schema, String table) {
    return jdbi.withHandle(handle ->
            handle.createQuery(
                            "SELECT a.attname FROM pg_attribute a " +
                                    "JOIN pg_class c     ON c.oid = a.attrelid " +
                                    "JOIN pg_namespace n ON n.oid = c.relnamespace " +
                                    "WHERE n.nspname = :schema AND c.relname = :table " +
                                    "  AND a.attname IN ('created_date', 'created_on') " +
                                    "  AND a.atttypid = 'timestamp'::regtype " +
                                    "  AND NOT a.attisdropped " +
                                    "  AND a.attnum > 0 " +
                                    "ORDER BY CASE a.attname " +
                                    "    WHEN 'created_date' THEN 1 " +
                                    "    WHEN 'created_on'   THEN 2 END " +
                                    "LIMIT 1")
                    .bind("schema", schema)
                    .bind("table", table)
                    .mapTo(String.class)
                    .findOne()
    );
  }

  /** Reads the source PK (name and columns in PK order) from pg_constraint. */
  private Optional<PkInfo> capturePk(Jdbi jdbi, String schema, String table) {
    final Optional<PkRow> row = jdbi.withHandle(handle ->
            handle.createQuery(
                            "SELECT con.conname, con.conkey::text AS conkey_text " +
                                    "FROM pg_constraint con " +
                                    "JOIN pg_class c     ON c.oid = con.conrelid " +
                                    "JOIN pg_namespace n ON n.oid = c.relnamespace " +
                                    "WHERE n.nspname = :schema AND c.relname = :table " +
                                    "  AND con.contype = 'p'")
                    .bind("schema", schema)
                    .bind("table", table)
                    .map((rs, ctx) -> new PkRow(rs.getString("conname"), rs.getString("conkey_text")))
                    .findOne()
    );
    if (!row.isPresent()) return Optional.empty();

    final List<Integer> attnums = parsePgIntArray(row.get().conkeyText);
    final List<String> columns = resolveColumnNames(jdbi, schema, table, attnums);
    return Optional.of(new PkInfo(row.get().conname, columns));
  }

  /** Returns non-PK indexes as column-list strings, e.g. ["(action_id)", "(root_pipeline_id, created_on)"]. */
  private List<String> captureIndexes(Jdbi jdbi, String schema, String table) {
    final List<IndexRow> rows = jdbi.withHandle(handle ->
            handle.createQuery(
                            "SELECT i.indexrelid::text AS index_oid, i.indkey::text AS indkey_text " +
                                    "FROM pg_index i " +
                                    "JOIN pg_class tc      ON tc.oid = i.indrelid " +
                                    "JOIN pg_namespace n   ON n.oid  = tc.relnamespace " +
                                    "WHERE n.nspname = :schema AND tc.relname = :table " +
                                    "  AND NOT i.indisprimary")
                    .bind("schema", schema)
                    .bind("table", table)
                    .map((rs, ctx) -> new IndexRow(rs.getString("index_oid"), rs.getString("indkey_text")))
                    .list()
    );

    final List<String> result = new ArrayList<>();
    for (IndexRow r : rows) {
      final List<Integer> attnums = parseSpaceSeparatedInts(r.indkeyText);
      if (attnums.isEmpty() || attnums.stream().anyMatch(n -> n <= 0)) continue;

      final List<String> colNames;
      try {
        colNames = resolveColumnNames(jdbi, schema, table, attnums);
      } catch (Exception e) {
        continue;
      }
      if (colNames.size() != attnums.size()) continue;

      final String colList = "(" + colNames.stream()
              .map(UniversalPartitioningScriptAction::quoteIdent)
              .collect(Collectors.joining(", ")) + ")";
      result.add(colList);
    }
    return result;
  }

  /** Finds the most recent dated partition (alphabetic last, excluding the default). */
  private Optional<String> findLatestDatedPartition(Jdbi jdbi, String schema, String table) {
    final String defaultName = table + "_default";
    return jdbi.withHandle(handle ->
            handle.createQuery(
                            "SELECT c2.relname FROM pg_inherits inh " +
                                    "JOIN pg_class c2      ON c2.oid = inh.inhrelid " +
                                    "JOIN pg_class pc      ON pc.oid = inh.inhparent " +
                                    "JOIN pg_namespace pn  ON pn.oid = pc.relnamespace " +
                                    "WHERE pn.nspname = :schema AND pc.relname = :table " +
                                    "  AND c2.relname <> :defaultName " +
                                    "ORDER BY c2.relname DESC LIMIT 1")
                    .bind("schema", schema)
                    .bind("table", table)
                    .bind("defaultName", defaultName)
                    .mapTo(String.class)
                    .findOne()
    );
  }

  private List<String> resolveColumnNames(Jdbi jdbi, String schema, String table, List<Integer> attnums) {
    final List<String> names = new ArrayList<>(attnums.size());
    for (int attnum : attnums) {
      final String name = jdbi.withHandle(handle ->
              handle.createQuery(
                              "SELECT a.attname FROM pg_attribute a " +
                                      "JOIN pg_class c     ON c.oid = a.attrelid " +
                                      "JOIN pg_namespace n ON n.oid = c.relnamespace " +
                                      "WHERE n.nspname = :schema AND c.relname = :table " +
                                      "  AND a.attnum = :attnum AND NOT a.attisdropped")
                      .bind("schema", schema)
                      .bind("table", table)
                      .bind("attnum", attnum)
                      .mapTo(String.class)
                      .one()
      );
      names.add(name);
    }
    return names;
  }

